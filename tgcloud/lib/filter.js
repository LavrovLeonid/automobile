// Решает, анонсирует ли пост канала старт продажи билетов.
// Пост проходит, если сработал хотя бы один INCLUDE и ни одного EXCLUDE.

const INCLUDE = [
  // «стартует продажа билетов», «старт продаж билетов», «открыта продажа билетов», «идут продажи билетов»
  /(старт\S*|начал\S*|начина\S*|начн[её]т\S*|открыт\S*|открыва\S*|ид[уеё]т)(\s+\S+){0,3}?\s+продаж\S*(\s+\S+){0,2}?\s+билет/iu,
  // «продажа билетов стартует / откроется»
  /продаж\S*\s+билет\S*(\s+\S+){0,4}?\s+(старт\S*|начн\S*|начина\S*|откро\S*|открыва\S*)/iu,
  // «старт билетных продаж»
  /(старт\S*|начал\S*|открыт\S*)\s+билетн\S*\s+продаж/iu,
  // Каждый анонс продаж содержит лимиты на покупку
  /лимит\S*\s+на\s+покупк/iu,
];

// Розыгрыши и их итоги тоже говорят про билеты, но это не продажа.
const EXCLUDE = [/розыгрыш|разыгрыва|победител|итоги/iu];

export function isTicketSale(text) {
  if (typeof text !== 'string' || !text) return false;
  if (EXCLUDE.some((re) => re.test(text))) return false;
  return INCLUDE.some((re) => re.test(text));
}
